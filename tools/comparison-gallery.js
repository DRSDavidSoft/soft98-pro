"use strict";

const fs = require("node:fs");
const path = require("node:path");
const previews = require("../src/option-previews.json");
const { locales } = require("../src/messages.json");
const { illustration } = require("./preview-illustrations.js");

const directory = path.resolve(__dirname, "../docs/assets/comparison");
const livePairs = {
  ...Object.fromEntries(
    ["blockAds", "pro", "compactLayout", "wideColumns", "hideAnnoyances", "utilityInHeader"].map(key =>
      [key, [`live/${key}-off.webp`, `live/${key}-on.webp`]])),
  expandMain: ["../settings/expand-off.webp", "../settings/expand-on.webp"],
};
const notes = {
  blockAds: "Live screenshots. With the switch off, the advertising cards remain beside the article. The ads themselves vary by visit.",
  patchScripts: "Illustration. The difference is in how the original script runs, not in the switch's appearance.",
  pro: "Live screenshots. Turning off this switch leaves the selected protection options running; it is not stock Soft98.",
  darkDesign: "Live screenshots. Off uses the Pro light palette, not the stock site.",
  rgbMode: "Live capture. The On preview animates; the still is available below in the same comparison.",
  expandMain: "Live screenshots taken after scrolling past the sidebar with Refined content layout enabled.",
  wideColumns: "Live screenshots at 2304 px, with Refined content layout enabled. On places related posts and downloads alongside the article.",
  quickNavigation: "Illustration. Off reloads the listing page; On replaces the listing without a full reload.",
  hideAnnoyances: "Live screenshots. Look for the offer to install the software at the bottom of the password and help panel.",
  utilityInHeader: "Live screenshots. Off keeps Useful software beside the article; On moves it into a dialog opened from the top bar.",
  taunt: "Illustration. The success message appears briefly after cleanup, not permanently.",
  diagnostics: "Illustration. The output is in the console, not on the page.",
  soundFeedback: "Illustration. This switch changes audio, which a still image cannot show.",
  recommendExtension: "Illustration. This recommendation applies to the userscript, not the browser extension.",
};

function syncGallery({ check = false } = {}) {
  const write = (file, content) => {
    const target = path.join(directory, file);
    if (!check) {
      fs.writeFileSync(target, content);
    } else if (!fs.existsSync(target) || fs.readFileSync(target, "utf8").replace(/\r\n/g, "\n") !== content) {
      throw new Error(`Gallery file out of date: ${file}. Run npm run docs:comparison.`);
    }
  };
  const asset = (file) => {
    const target = path.join(directory, file);
    if (!fs.existsSync(target) || !fs.statSync(target).size) throw new Error(`Gallery image missing: ${file}`);
    return file;
  };
  const controls = locales.en.runtime.controlOptions;
  const sliderKeys = Object.keys(controls);
  if (Object.keys(previews).length !== sliderKeys.length || sliderKeys.some(key => !Object.hasOwn(previews, key))) {
    throw new Error("Comparison gallery must have one pair per Control Center switch");
  }

  const sections = sliderKeys.map((key) => {
    const { title, detail } = controls[key];
    const preview = previews[key];
    const illustrated = preview === "illustration" && !livePairs[key];
    const files = livePairs[key] || (illustrated ? [false, true].map((on) => {
      const file = `illustrations/${key}-${on ? "on" : "off"}.svg`;
      write(file, illustration(key, on));
      return file;
    }) : preview.map(file => `../settings/${file}`));
    return [
      "<details>", `<summary><strong>${title}</strong></summary>`, "",
      detail, "", notes[key] || (illustrated ? "Illustration." : "Live screenshots."), "",
      "**Off**", "", `![${title}: Off](${asset(files[0])})`, "",
      "**On**", "", `![${title}: On](${asset(files[1])})`, "",
      ...(files[2] ? [`[View a still frame](${asset(files[2])})`, ""] : []),
      "</details>",
    ].join("\n");
  });
  write("README.md", [
    "<!-- Generated by tools/comparison-gallery.js. Run npm run docs:comparison to refresh. -->",
    "# Soft98 vs Soft98 Pro", "",
    "The same [AnyDesk download tab](https://soft98.ir/internet/remote-control/15737-anydesk-download.html) captured in two clean Firefox profiles at the same window size. The control panel is closed.", "",
    "## Before: Stock Soft98", "",
    "Live Soft98 as served to a clean browser: no Soft98 Pro, userscript, ad blocker, or injected styles.", "",
    `![Stock Soft98 download tab, with the original light theme and ads](${asset("downloads-before.png")})`, "",
    "## After: Soft98 Pro", "",
    "The live download tab with the Soft98 Pro extension installed and its default settings enabled.", "",
    `![Soft98 Pro download tab with the default dark theme](${asset("../soft98-pro-dark.png")})`, "",
    "## Individual switches", "",
    "Expand a section for its Off and On views. These compare one setting inside Soft98 Pro, keeping the other relevant settings fixed. Off here does not mean the extension was uninstalled. Illustrations are labeled where a live still does not reliably show the behavior.", "",
    sections.join("\n\n"), "",
    "## More views", "",
    "- [Narrow-screen download view](downloads-mobile-after.png) and [ultrawide layout](header-ultrawide.png)",
    "- [Windows 11 listing](windows-listing.png) and [expanded article](article-expanded.png)",
    "- [Stock utility card](utility-before.png) and [Pro utility card](utility-after.png)",
    "- [Download manager and multipart archives](../../wiki/Download-Manager.md)",
    "- [Platform and product artwork sources and licenses](../../../src/assets/utility/README.md)", "",
    "Platform artwork includes [Tabler Icons](https://github.com/tabler/tabler-icons) (MIT), [Simple Icons](https://simpleicons.org/) (CC0), and original Soft98 Pro artwork. Product marks belong to their respective owners.", "",
  ].join("\n"));
}

if (require.main === module) {
  const check = process.argv.includes("--check");
  if (!check) fs.mkdirSync(path.join(directory, "illustrations"), { recursive: true });
  syncGallery({ check });
}

module.exports = { syncGallery };
